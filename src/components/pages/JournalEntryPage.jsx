function JeDetailModal({ t, entry, documentTypeLabel, companyName, onClose, language = "es", initialShowHistory = false }) {
  const totalDebit = (entry.items || []).reduce((s, i) => s + (i.debit || 0), 0);
  const totalCredit = (entry.items || []).reduce((s, i) => s + (i.credit || 0), 0);

  // Bloque A (2026-11-21): previous versions of this entry, loaded on demand
  // (GET /history). Each one is the entry exactly as it was before an edit
  // or the annulment, with who changed it and when.
  const [showHistory, setShowHistory] = useState(initialShowHistory);
  const [history, setHistory] = useState(null); // null = not loaded yet
  const [historyError, setHistoryError] = useState("");

  const loadHistory = async () => {
    setHistoryError("");
    try {
      const response = await api.get(`/v1/journal-entries/${entry.id}/history`);
      setHistory(Array.isArray(response.data?.data) ? response.data.data : []);
    } catch (error) {
      setHistory([]);
      setHistoryError(getApiErrorMessage(error, language, t.errorConn));
    }
  };

  // Opened from the list's history icon: load it right away.
  useEffect(() => {
    if (initialShowHistory) loadHistory();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const toggleHistory = async () => {
    const next = !showHistory;
    setShowHistory(next);
    if (!next || history !== null) return;
    await loadHistory();
  };

  // NEW (2026-09-30): print the voucher as a standalone PDF, launched from
  // inside "Ver" rather than a separate button on the list row -- opening
  // the detail first is the natural review-before-printing step, and it
  // avoids a fourth button crowding Ver/Editar/Anular on narrow screens
  // (see pendientes.md for the fuller reasoning). No signature lines --
  // this isn't handed to someone else to sign, just the voucher for the
  // user's own record. The only timestamp is when it was PRINTED, taken
  // client-side at the moment of the click (there's no server-side
  // "generation" step to date instead, unlike the list's own PDF export).
  const handlePrintPdf = () => {
    const doc = new jsPDF({ orientation: "landscape" });

    const headerInfo = {
      companyName,
      reportTitle: `${t.voucherTitle} — ${entry.documentNumber}`,
      period: [entry.entryDate, documentTypeLabel(entry)].filter(Boolean).join("   ·   "),
      generatedAtLabel: t.printedAtLabel,
      generatedAt: nowLocalIso(),
    };

    let cursorY = addPdfReportHeader(doc, headerInfo);

    if (entry.description) {
      doc.setFontSize(9);
      doc.setTextColor(60);
      doc.text(entry.description, 14, cursorY);
      doc.setTextColor(0);
      cursorY += 6;
    }

    if (entry.annulled) {
      doc.setFontSize(9);
      doc.setTextColor(185, 28, 28);
      doc.text(`${t.annulled}${entry.annulmentReason ? `: ${entry.annulmentReason}` : ""}`, 14, cursorY);
      doc.setTextColor(0);
      cursorY += 6;
    }

    const body = (entry.items || []).map((item) => [
      `${item.accountCode} - ${item.accountName}`,
      truncateDetail(item.description),
      thirdPartyLabel(item.thirdPartyIdNumber, item.thirdPartyName),
      item.costCenterName || "—",
      money(item.debit),
      money(item.credit),
    ]);
    body.push([t.totalsRow, "", "", "", money(totalDebit), money(totalCredit)]);

    // Same "continuation pages get a running header too" pattern used by
    // every other PDF export in this app -- a voucher is usually short,
    // but a long multi-line entry can still overflow one page.
    const pageBeforeTable = doc.internal.getCurrentPageInfo().pageNumber;

    autoTable(doc, {
      startY: cursorY,
      head: [[t.account, t.description, t.thirdParty, t.costCenter, t.debit, t.credit]],
      body,
      styles: { fontSize: 9 },
      headStyles: { fillColor: [30, 41, 59] },
      columnStyles: {
        1: { cellWidth: 45 },
        4: { halign: "right" },
        5: { halign: "right" },
      },
      margin: { top: 20, bottom: 15 },
      didDrawPage: (data) => {
        if (data.pageNumber > pageBeforeTable) {
          addPdfRunningHeader(doc, headerInfo);
        }
      },
    });

    doc.save(`${t.voucherTitle.replace(/\s+/g, "_")}_${entry.documentNumber}.pdf`);
  };

  // NEW (2026-10-24, user request): Excel export of this same voucher,
  // same column order as the PDF/on-screen table above (Cuenta,
  // Descripcion, Tercero, Centro de Costo, Debito, Credito) -- but unlike
  // the PDF (fixed page width) and the on-screen table (narrow column +
  // title tooltip), this keeps each line's FULL description text: Excel
  // cells have no print-layout space constraint, so there's no reason to
  // truncate via truncateDetail() here.
  const handleExportExcel = () => {
    const headerInfo = {
      companyName,
      reportTitle: `${t.voucherTitle} — ${entry.documentNumber}`,
      period: [entry.entryDate, documentTypeLabel(entry)].filter(Boolean).join("   ·   "),
      generatedAtLabel: t.printedAtLabel,
      generatedAt: nowLocalIso(),
    };

    const rows = [
      ...buildExcelHeaderRows(headerInfo),
      [t.account, t.description, t.thirdParty, t.costCenter, t.debit, t.credit],
      ...(entry.items || []).map((item) => [
        `${item.accountCode} - ${item.accountName}`,
        item.description || "—",
        thirdPartyLabel(item.thirdPartyIdNumber, item.thirdPartyName),
        item.costCenterName || "—",
        item.debit || 0,
        item.credit || 0,
      ]),
      [t.totalsRow, "", "", "", totalDebit, totalCredit],
    ];

    const sheet = XLSX.utils.aoa_to_sheet(rows);
    const workbook = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(workbook, sheet, t.voucherTitle.slice(0, 31));
    XLSX.writeFile(workbook, `${t.voucherTitle.replace(/\s+/g, "_")}_${entry.documentNumber}.xlsx`);
  };

  return (
    <Modal
      size="lg"
      title={`${t.detailTitle} — ${entry.documentNumber}`}
      subtitle={`${entry.entryDate}${entry.description ? ` · ${entry.description}` : ""}`}
      onClose={onClose}
      closeLabel={t.close}
      footer={
        <>
          <Button variant="ghost" onClick={onClose}>{t.close}</Button>
          <Button variant="ghost" onClick={toggleHistory}>{showHistory ? t.historyHide : t.historyButton}</Button>
          <Button variant="secondary" onClick={handleExportExcel}>{t.exportExcel}</Button>
          <Button variant="primary" onClick={handlePrintPdf}>{t.printPdf}</Button>
        </>
      }
    >
      {entry.annulled && (
        <Alert tone="error" className="mb-4" title={t.annulled}>
          {entry.annulmentReason || null}
          {entry.reversalDocumentNumber && (
            <div className={entry.annulmentReason ? "mt-1" : ""}>{t.reversedNotice.replace("{doc}", entry.reversalDocumentNumber)}</div>
          )}
        </Alert>
      )}
      {entry.reversalOfDocumentNumber && (
        <Alert tone="info" className="mb-4" title={`${t.reversalOf} ${entry.reversalOfDocumentNumber}`}>
          {t.reversalNotice.replace("{doc}", entry.reversalOfDocumentNumber)}
        </Alert>
      )}

      <div className="overflow-x-auto">
        <table className={tbl.table}>
          <thead className={tbl.thead}>
            <tr>
              <th scope="col" className={tbl.th}>{t.account}</th>
              <th scope="col" className={tbl.th}>{t.description}</th>
              <th scope="col" className={tbl.th}>{t.thirdParty}</th>
              <th scope="col" className={tbl.th}>{t.costCenter}</th>
              <th scope="col" className={tbl.thNum}>{t.debit}</th>
              <th scope="col" className={tbl.thNum}>{t.credit}</th>
            </tr>
          </thead>
          <tbody className={tbl.tbody}>
            {(entry.items || []).map((item) => (
              <tr key={item.id}>
                <td className={tbl.td}>
                  <span className="font-semibold text-slate-900">{item.accountCode}</span> {item.accountName}
                </td>
                <td className={`${tbl.td} text-xs`} title={item.description || ""}>{truncateDetail(item.description)}</td>
                <td className={`${tbl.td} text-xs`}>{thirdPartyLabel(item.thirdPartyIdNumber, item.thirdPartyName)}</td>
                <td className={`${tbl.td} text-xs`}>{item.costCenterName || "—"}</td>
                <td className={tbl.tdNum}>{money(item.debit)}</td>
                <td className={tbl.tdNum}>{money(item.credit)}</td>
              </tr>
            ))}
          </tbody>
          <tfoot className={tbl.tfoot}>
            <tr>
              <td className={tbl.td} colSpan={4}>Total</td>
              <td className={`${tbl.tdNum} font-bold`}>{money(totalDebit)}</td>
              <td className={`${tbl.tdNum} font-bold`}>{money(totalCredit)}</td>
            </tr>
          </tfoot>
        </table>
      </div>

      {showHistory && (
        <JeHistoryPanel t={t} history={history} error={historyError} />
      )}
    </Modal>
  );
}

